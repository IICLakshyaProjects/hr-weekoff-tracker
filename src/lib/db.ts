import { Pool, types, type PoolClient } from "pg";
import { hashPassword } from "./password";

// Return DATE columns as plain "YYYY-MM-DD" strings (no timezone shifting) and BIGINT counts as numbers.
types.setTypeParser(1082, (v) => v);
types.setTypeParser(20, (v) => Number(v));

/** Timezone used for "Date of Request" and log timestamps. */
export const APP_TZ = process.env.APP_TIMEZONE ?? "Asia/Kolkata";

export type Exec = {
  /** All rows. Use $1, $2… placeholders. */
  q<T = Record<string, unknown>>(sql: string, params?: unknown[]): Promise<T[]>;
  /** First row or undefined. */
  one<T = Record<string, unknown>>(sql: string, params?: unknown[]): Promise<T | undefined>;
  /** Number of affected rows. */
  run(sql: string, params?: unknown[]): Promise<number>;
};

const g = globalThis as unknown as { __hrPool?: Pool; __hrReady?: Promise<void> };

function pool(): Pool {
  if (!g.__hrPool) {
    if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL is not set (see .env)");
    g.__hrPool = new Pool({ connectionString: process.env.DATABASE_URL, max: 5 });
  }
  return g.__hrPool;
}

function wrap(runner: Pool | PoolClient): Exec {
  return {
    async q(sql, params) {
      return (await runner.query(sql, params)).rows;
    },
    async one(sql, params) {
      return (await runner.query(sql, params)).rows[0];
    },
    async run(sql, params) {
      return (await runner.query(sql, params)).rowCount ?? 0;
    },
  };
}

/** Database handle; creates the schema and seeds the admin on first use. */
export async function db(): Promise<Exec> {
  g.__hrReady ??= init().catch((err) => {
    g.__hrReady = undefined; // retry on next call
    throw err;
  });
  await g.__hrReady;
  return wrap(pool());
}

export async function tx<T>(fn: (e: Exec) => Promise<T>): Promise<T> {
  await db();
  const client = await pool().connect();
  try {
    await client.query("BEGIN");
    const result = await fn(wrap(client));
    await client.query("COMMIT");
    return result;
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
  }
}

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS employees (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_code         TEXT NOT NULL,
    name             TEXT NOT NULL,
    email            TEXT,
    phone            TEXT,
    department       TEXT,
    designation      TEXT,
    business_unit    TEXT,
    location         TEXT,
    band             TEXT,
    role             TEXT NOT NULL DEFAULT 'EMPLOYEE' CHECK (role IN ('ADMIN','HEAD','EMPLOYEE')),
    manager_id       INTEGER REFERENCES employees(id) ON DELETE SET NULL,
    portal_access    BOOLEAN NOT NULL DEFAULT FALSE,
    can_edit_weekoff BOOLEAN NOT NULL DEFAULT FALSE,
    default_weekoff  TEXT,
    status           TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    password_hash    TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE UNIQUE INDEX IF NOT EXISTS ux_emp_code ON employees (lower(emp_code));
  CREATE UNIQUE INDEX IF NOT EXISTS ux_emp_email ON employees (lower(email));
  CREATE INDEX IF NOT EXISTS ix_emp_manager ON employees (manager_id);

  CREATE TABLE IF NOT EXISTS weekoffs (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    date        DATE NOT NULL,
    note        TEXT,
    marked_by   INTEGER REFERENCES employees(id) ON DELETE SET NULL,
    marked_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (employee_id, date)
  );
  CREATE INDEX IF NOT EXISTS ix_weekoff_date ON weekoffs (date);

  CREATE TABLE IF NOT EXISTS month_locks (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department  TEXT NOT NULL,
    month       TEXT NOT NULL,
    locked_by   INTEGER REFERENCES employees(id) ON DELETE SET NULL,
    locked_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (department, month)
  );

  CREATE TABLE IF NOT EXISTS sessions (
    token       TEXT PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    expires_at  TIMESTAMPTZ NOT NULL
  );

  CREATE TABLE IF NOT EXISTS activity_log (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id  INTEGER REFERENCES employees(id) ON DELETE SET NULL,
    action    TEXT NOT NULL,
    details   TEXT,
    at        TIMESTAMPTZ NOT NULL DEFAULT now()
  );
`;

async function init() {
  const e = wrap(pool());
  await e.run(SCHEMA);

  // Seed a first administrator so the portal can be used out of the box.
  const admins = await e.one<{ c: number }>("SELECT COUNT(*)::int AS c FROM employees WHERE role = 'ADMIN'");
  if (!admins?.c) {
    await e.run(
      `INSERT INTO employees (emp_code, name, email, role, portal_access, can_edit_weekoff, password_hash, department, designation)
       VALUES ($1, 'Administrator', $2, 'ADMIN', TRUE, TRUE, $3, 'HR', 'Administrator')
       ON CONFLICT DO NOTHING`,
      [process.env.ADMIN_EMP_ID ?? "ADMIN001", process.env.ADMIN_EMAIL ?? "hr@iiclakshya.com", hashPassword(process.env.ADMIN_PASSWORD ?? "HRLak@2026")],
    );
  }
  await applyHeadDefaults(e);
}

/**
 * Department Heads can log in and mark week offs for their team (and themselves).
 * Any head that has never had a password gets login access, week-off permission and the
 * default head password (HEAD_DEFAULT_PASSWORD, "Admin@123" for now). Heads that already
 * have a password are left alone, so an admin can still revoke a particular head's access.
 */
export async function applyHeadDefaults(e?: Exec): Promise<number> {
  const ex = e ?? (await db());
  const pending = await ex.one<{ c: number }>("SELECT COUNT(*)::int AS c FROM employees WHERE role = 'HEAD' AND password_hash IS NULL");
  if (!pending?.c) return 0;
  return ex.run(
    `UPDATE employees SET portal_access = TRUE, can_edit_weekoff = TRUE, password_hash = $1, updated_at = now()
     WHERE role = 'HEAD' AND password_hash IS NULL`,
    [hashPassword(process.env.HEAD_DEFAULT_PASSWORD ?? "Admin@123")],
  );
}

export async function logActivity(actorId: number | null, action: string, details?: string, e?: Exec) {
  await (e ?? (await db())).run("INSERT INTO activity_log (actor_id, action, details) VALUES ($1, $2, $3)", [actorId, action, details ?? null]);
}

/** "$1, $2, …" for an IN (...) list starting at position `start`. */
export function placeholders(count: number, start = 1): string {
  return Array.from({ length: count }, (_, i) => `$${start + i}`).join(", ");
}
